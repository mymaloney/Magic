-- Lists which synced cards the Lua engine supports, and what blocks the rest.
-- Run from the repository root:
--   luajit solarus/tools/support_report.lua > solarus/cardpool/support_report.md

package.path = "solarus/quest/data/?.lua;" .. package.path
local card_db = require("scripts/mtg/card_db")

local function read(path)
  local f = assert(io.open(path, "rb"))
  local s = f:read("*a")
  f:close()
  return s
end

local pool = dofile("solarus/quest/data/cards/pool.lua")
local db = card_db.new(pool, function(path) return read("solarus/quest/data/" .. path) end)

local supported, reasons, blocked_by_one = {}, {}, {}
for _, def in ipairs(db.list) do
  if def.supported then
    supported[#supported + 1] = def.name
  else
    for _, reason in ipairs(def.unsupported) do
      reasons[reason] = reasons[reason] or {}
      table.insert(reasons[reason], def.name)
    end
    if #def.unsupported == 1 then
      local reason = def.unsupported[1]
      blocked_by_one[reason] = (blocked_by_one[reason] or 0) + 1
    end
  end
end

local sorted = {}
for reason, cards in pairs(reasons) do
  sorted[#sorted + 1] = { reason = reason, cards = cards }
end
table.sort(sorted, function(a, b)
  local ua, ub = blocked_by_one[a.reason] or 0, blocked_by_one[b.reason] or 0
  if ua ~= ub then
    return ua > ub
  end
  if #a.cards ~= #b.cards then
    return #a.cards > #b.cards
  end
  return a.reason < b.reason
end)

print("# Engine support report")
print("")
print("Generated by `solarus/tools/support_report.lua`; re-run after engine changes.")
print("")
print(string.format("**%d of %d synced cards are supported.**", #supported, #db.list))
print("")
print("## Supported")
print("")
print(table.concat(supported, ", "))
print("")
print("## What blocks the rest")
print("")
print("\"Only blocker\" = cards for which this is the last missing feature, so implementing it")
print("unlocks them immediately. Sorted by that, then by total cards affected.")
print("")
print("| Missing feature | Only blocker for | Cards affected | Examples |")
print("|---|---|---|---|")
for _, entry in ipairs(sorted) do
  table.sort(entry.cards)
  local examples = table.concat(entry.cards, ", ", 1, math.min(4, #entry.cards))
  if #entry.cards > 4 then
    examples = examples .. ", …"
  end
  print(string.format("| %s | %d | %d | %s |", entry.reason:gsub("|", "\\|"), blocked_by_one[entry.reason] or 0, #entry.cards, examples))
end
