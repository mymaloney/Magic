#!/usr/bin/env python3
"""Copy a card pool's Forge scripts into the Solarus quest and write its Lua index.

Usage: python3 solarus/tools/sync_cards.py solarus/cardpool/maloney_foundations.txt solarus/cardpool/basic_lands.txt

Takes one or more pool files (their entries are combined). Writes solarus/quest/data/cards/<script>.txt (verbatim copies of the Forge scripts) and
solarus/quest/data/cards/pool.lua, which returns { {file=..., name=..., copies=n}, ... }.
Stale .txt files in the cards folder are removed. Re-run after editing the pool or after
merging upstream Forge.
"""

import argparse
import collections
import pathlib
import shutil
import sys

from cardpool_report import REPO, index_scripts, read_pool

CARDS_DIR = REPO / "solarus" / "quest" / "data" / "cards"


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pools", type=pathlib.Path, nargs="+")
    args = ap.parse_args()

    index = index_scripts()
    counts = collections.Counter()
    for pool in args.pools:
        counts.update(read_pool(pool))
    missing = [n for n in counts if n.lower() not in index]
    if missing:
        sys.exit("No Forge script for: " + ", ".join(missing))

    CARDS_DIR.mkdir(parents=True, exist_ok=True)
    wanted = {}
    for name in counts:
        src = index[name.lower()]
        if src.name in wanted and wanted[src.name] != src:
            sys.exit(f"Two scripts share the file name {src.name}")
        wanted[src.name] = src

    for old in CARDS_DIR.glob("*.txt"):
        if old.name not in wanted:
            old.unlink()
    for fname, src in wanted.items():
        shutil.copyfile(src, CARDS_DIR / fname)

    sources = ", ".join(p.name for p in args.pools)
    lines = ["-- Generated by solarus/tools/sync_cards.py from " + sources + ". Do not edit.",
             "return {"]
    for name in sorted(counts):
        fname = index[name.lower()].name
        lines.append(f"  {{ file = {lua_string(fname)}, name = {lua_string(name)}, copies = {counts[name]} }},")
    lines.append("}")
    (CARDS_DIR / "pool.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Synced {len(wanted)} scripts ({sum(counts.values())} cards) into {CARDS_DIR.relative_to(REPO)}")


if __name__ == "__main__":
    main()
