#!/usr/bin/env python3
"""Report which Forge scripts and rules features a GBA card pool needs.

Usage: python3 solarus/tools/cardpool_report.py solarus/cardpool/maloney_foundations.txt [-o report.md]

The pool file is one card name per line (repeat a line for multiple copies);
lines starting with '#' and blank lines are ignored. Card names are matched
against the Name: line of every script in forge-gui/res/cardsfolder.
"""

import argparse
import collections
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
CARDSFOLDER = REPO / "forge-gui" / "res" / "cardsfolder"
TOKENSCRIPTS = REPO / "forge-gui" / "res" / "tokenscripts"

API_RE = re.compile(r"\b(?:SP|AB|DB)\$ ?([A-Za-z]+)")
TRIGGER_RE = re.compile(r"^T:Mode\$ ?([A-Za-z]+)")
STATIC_RE = re.compile(r"^S:Mode\$ ?([A-Za-z]+)")
REPLACE_RE = re.compile(r"^R:Event\$ ?([A-Za-z]+)")
KEYWORD_RE = re.compile(r"^K:([^:]+)")
TOKEN_RE = re.compile(r"TokenScript\$ ?([A-Za-z0-9_,]+)")
COST_RE = re.compile(r"Cost\$ ?([^|]+)")


def index_scripts():
    """Map every face name (case-insensitive) to its script path."""
    index = {}
    for path in CARDSFOLDER.rglob("*.txt"):
        if "upcoming" in path.parts or "rebalanced" in path.parts:
            continue
        with path.open(encoding="utf-8") as f:
            for line in f:
                if line.startswith("Name:"):
                    index.setdefault(line[5:].strip().lower(), path)
    return index


def read_pool(path):
    names = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            names.append(line)
    return names


def analyse(script):
    feats = collections.defaultdict(set)
    for line in script.read_text(encoding="utf-8").splitlines():
        for m in API_RE.finditer(line):
            feats["Effect API"].add(m.group(1))
        for rx, kind in ((TRIGGER_RE, "Trigger mode"), (STATIC_RE, "Static mode"),
                         (REPLACE_RE, "Replacement event"), (KEYWORD_RE, "Keyword")):
            m = rx.match(line)
            if m:
                feats[kind].add(m.group(1).strip())
        for m in TOKEN_RE.finditer(line):
            for tok in m.group(1).split(","):
                feats["Token"].add(tok)
        if line.startswith("AlternateMode:"):
            feats["Card layout"].add(line.split(":", 1)[1].strip())
        if line.startswith("ManaCost:") and re.search(r"[WUBRG]/[WUBRGP2]", line):
            feats["Mana cost"].add("hybrid/phyrexian")
    return feats


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pool", type=pathlib.Path)
    ap.add_argument("-o", "--output", type=pathlib.Path)
    args = ap.parse_args()

    index = index_scripts()
    pool = read_pool(args.pool)
    counts = collections.Counter(pool)

    missing = [n for n in counts if n.lower() not in index]
    found = {n: index[n.lower()] for n in counts if n.lower() in index}

    usage = collections.defaultdict(lambda: collections.defaultdict(list))
    for name, path in sorted(found.items()):
        for kind, values in analyse(path).items():
            for v in values:
                usage[kind][v].append(name)

    out = []
    out.append(f"# Card pool report: `{args.pool.name}`\n")
    out.append("Generated by `solarus/tools/cardpool_report.py`; re-run after editing the pool.\n")
    out.append(f"- Entries: {len(pool)} ({len(counts)} distinct cards)")
    out.append(f"- Scripts found: {len(found)}")
    out.append(f"- Missing from Forge: {len(missing)}\n")
    if missing:
        out.append("## Missing cards\n")
        out.extend(f"- {n}" for n in missing)
        out.append("")
    out.append("## Scripts\n")
    out.append("| Card | Copies | Script |")
    out.append("|---|---|---|")
    for name, path in sorted(found.items()):
        out.append(f"| {name} | {counts[name]} | `{path.relative_to(REPO)}` |")
    out.append("")
    for kind in ("Effect API", "Keyword", "Trigger mode", "Static mode",
                 "Replacement event", "Token", "Card layout", "Mana cost"):
        if kind not in usage:
            continue
        out.append(f"## {kind} ({len(usage[kind])})\n")
        out.append("| Feature | Cards | Used by |")
        out.append("|---|---|---|")
        for feat, cards in sorted(usage[kind].items(), key=lambda kv: (-len(kv[1]), kv[0])):
            shown = ", ".join(sorted(cards)[:6]) + (" …" if len(cards) > 6 else "")
            out.append(f"| {feat} | {len(cards)} | {shown} |")
        out.append("")

    text = "\n".join(out)
    if args.output:
        args.output.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
